async function role(page: any, name: string, person?: string) {
  await page.locator('button[aria-haspopup="true"]').first().click()
  await page.locator('#role-sel').selectOption(name)
  if (person) await page.locator('#person-sel').selectOption({ label: person })
  await page.locator('button[aria-haspopup="true"]').first().click()
}

