test('Browser scrolls the page while the compact sidebar stays in place', async ({ page }) => {
  await page.setViewportSize({ width: 1280, height: 768 })
  await page.goto('/#/bills'); await role(page, 'Administrator')
  await expect(page.locator('main table tbody tr').first()).toBeVisible()
  const nav = page.getByRole('navigation', { name: 'Main', exact: true })
  const content = page.locator('[data-page-content]')
  expect(await content.evaluate(el => getComputedStyle(el).overflowY)).toBe('visible')
  const menu = nav.locator('ul')
  const collapse = nav.getByRole('button', { name: 'Collapse navigation' })
  expect(await menu.evaluate(el => el.scrollHeight <= el.clientHeight)).toBe(true)
  await expect(nav.getByRole('link', { name: 'Admin', exact: true })).toBeInViewport()
  expect(await menu.evaluate(el => getComputedStyle(el).scrollbarWidth)).toBe('none')
  await page.setViewportSize({ width: 1280, height: 600 })
  const initialNavTop = await nav.evaluate(el => el.getBoundingClientRect().top)
  const initialMainTop = await page.locator('main').evaluate(el => el.getBoundingClientRect().top)
  const initialCollapseTop = await collapse.evaluate(el => el.getBoundingClientRect().top)
  await page.evaluate(() => window.scrollTo(0, 400))
  const offset = await page.evaluate(() => window.scrollY)
  expect(offset).toBeGreaterThan(0)
  expect(await content.evaluate(el => el.scrollTop)).toBe(0)
  expect(await nav.evaluate(el => el.getBoundingClientRect().top)).toBeCloseTo(initialNavTop)
  expect(await page.locator('main').evaluate(el => el.getBoundingClientRect().top)).toBeCloseTo(initialMainTop - offset)
  expect(await menu.evaluate(el => el.scrollTop)).toBe(0)
  await menu.evaluate(el => el.scrollTo(0, el.scrollHeight))
  expect(await menu.evaluate(el => el.scrollTop)).toBeGreaterThan(0)
  await expect(nav.getByRole('link', { name: 'Admin', exact: true })).toBeInViewport()
  await expect(collapse).toBeInViewport()
  expect(await collapse.evaluate(el => el.getBoundingClientRect().top)).toBeCloseTo(initialCollapseTop)
  expect(await page.evaluate(() => window.scrollY)).toBe(offset)
  await collapse.click()
  await expect(nav.getByRole('button', { name: 'Expand navigation' })).toBeInViewport()
  await nav.getByRole('link', { name: 'Admin', exact: true }).click()
  await expect(page.locator('main h1').first()).toBeInViewport()
  expect(await page.evaluate(() => window.scrollY)).toBe(0)
})

